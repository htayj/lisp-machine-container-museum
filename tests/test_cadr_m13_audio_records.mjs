import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { encodeCdrPcm1, parseCdrM11Open1, parseCdrPcm1, sha256Hex } from
  "../cadr-web/browser/cadr-m13-audio-record.mjs";

const open = Uint8Array.from([
  0x43,0x44,0x52,0x4d,0x31,0x31,0x4f,0x31, 0x01,0x00,0x00,0x00,0x30,0x00,0x00,0x00,
  0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00, 0x02,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0xbc,0x02,0x00,0x00,0x00,0x00,0x00,0x00, 0x03,0x00,0x00,0x00,0x02,0x00,0x00,0x00,
]);
assert.deepEqual(parseCdrM11Open1(open), { generation: 1n, consumerEpoch: 2n,
  queuePackets: 3, queuedFrames: 700, rendererProfile: 2 });
for (const offset of [0, 8, 12, 44]) { const bad = open.slice(); bad[offset] ^= 1; assert.equal(parseCdrM11Open1(bad), null); }

const literal = Uint8Array.from([
  0x43,0x44,0x52,0x50,0x43,0x4d,0x31,0x00, 0x01,0x00,0x40,0x00,0x00,0x00,0x00,0x00,
  0x42,0x00,0x00,0x00,0x40,0x1f,0x00,0x00, 0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x02,0x00,0x00,0x00,0x00,0x00,0x00,0x00, 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x00,0x00,0x00,0x00,0x01,0x00,0x00,0x00, 0x01,0x00,0x01,0x00,0x02,0x00,0x00,0x00,
  0x34,0x12,
]);
const record = encodeCdrPcm1({ generation: 1n, consumerEpoch: 2n, sequence: 0n,
  frameOffset: 0, samples: Uint8Array.from([0x34, 0x12]) });
assert.deepEqual(new Uint8Array(record), literal, "encoder matches independent literal vector");
const parsed = parseCdrPcm1(record);
assert.deepEqual({ ...parsed, samples: [...new Int16Array(parsed.samples)] }, {
  generation: 1n, consumerEpoch: 2n, sequence: 0n, frameOffset: 0,
  frameCount: 1, samples: [0x1234] });
assert.equal(await sha256Hex(record), createHash("sha256").update(new Uint8Array(record)).digest("hex"));
for (const offset of [0, 8, 10, 12, 16, 20]) {
  const bad = record.slice(0); new Uint8Array(bad)[offset] ^= 1;
  assert.equal(parseCdrPcm1(bad), null, `fixed header mutation ${offset}`);
}
for (let offset = 52; offset < 64; offset += 1) {
  const bad = literal.slice(); bad[offset] ^= 1;
  assert.equal(parseCdrPcm1(bad), null, `normative tail byte mutation ${offset}`);
}
const legacyNarrowTail = Uint8Array.from([
  0x43,0x44,0x52,0x50,0x43,0x4d,0x31,0x00, 0x01,0x00,0x40,0x00,0x00,0x00,0x00,0x00,
  0x42,0x00,0x00,0x00,0x40,0x1f,0x00,0x00, 0x01,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x02,0x00,0x00,0x00,0x00,0x00,0x00,0x00, 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
  0x00,0x00,0x00,0x00,0x01,0x00,0x01,0x00, 0x01,0x00,0x02,0x00,0x00,0x00,0x00,0x00,
  0x34,0x12,
]);
assert.equal(parseCdrPcm1(legacyNarrowTail), null,
  "parser rejects the displaced u16-count/u16-profile tail rather than aliasing it");
for (const count of [0, 513]) {
  const bad = record.slice(0); new DataView(bad).setUint32(52, count, true);
  assert.equal(parseCdrPcm1(bad), null);
}
assert.throws(() => encodeCdrPcm1({ generation: 1n, consumerEpoch: 1n, sequence: 0n,
  frameOffset: 0, samples: new ArrayBuffer(0) }));
assert.throws(() => encodeCdrPcm1({ generation: 1n, consumerEpoch: 1n, sequence: 0n,
  frameOffset: 512, samples: new Int16Array([1]) }), /frame range/);
console.log("cadr M13 CDRM11O1/CDRPCM1 layout and mutation tests passed");
